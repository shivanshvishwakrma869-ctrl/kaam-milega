/**
 * Render an icon as an SVG string.
 * @param {string} name  key from PATHS
 * @param {{size?:number, className?:string, title?:string, strokeWidth?:number}} [opts]
 * @returns {string} SVG markup (safe: no interpolation of untrusted data)
 */
export function icon(name, opts = {}) {
  const body = PATHS[name];
  if (!body) {
    if (import.meta.env?.DEV) console.warn(`[icons] unknown icon: ${name}`);
    return '';
  }
  const { size = 24, className = '', title, strokeWidth = 2 } = opts;

  // A titled icon is meaningful; an untitled one is decorative.
  const a11y = title
    ? `role="img" aria-label="${escapeAttr(title)}"`
    : 'aria-hidden="true" focusable="false"';

  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" ` +
    `viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" ` +
    `stroke-linecap="round" stroke-linejoin="round" ` +
    `${className ? `class="${escapeAttr(className)}" ` : ''}${a11y}>${body}</svg>`
  );
}

/** Icon names are developer-controlled, but attributes are escaped anyway. */
function escapeAttr(value) {
  return String(value).replace(/[&<>"']/g, (c) => {
    return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
  });
}

